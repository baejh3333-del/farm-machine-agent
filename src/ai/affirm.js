// 사용자의 짧은 답이 "실행해도 된다"는 긍정인지 판단한다. 서버(쓰기 승인 확인)와 화면(채팅 "네"로 확인 카드 실행)이 같은 규칙을 쓴다.

const AFFIRMATIVE = [
  /^(?:네+|넵|예+|응+|웅|어+|그래(?:요)?|좋아(?:요)?|좋습니다|ㅇㅇ+|ㅇㅋ+|오케이|ok(?:ay)?|콜|맞아(?:요)?|부탁(?:해요|드려요|합니다))$/i,
  // 사투리 대답: 경상(하모·좋심더·맞심더), 전라(야·그라제·맞당께), 충청(그려·그려유·기여)
  /^(?:하모(?:요)?|그려(?:유|요)?|그랴|기여|그라제|그라지|그럼(?:요)?|좋심더|맞심더|맞어|맞소|맞당께|예예|야)$/,
  // "응 해줘", "바로 해줘", "그렇게 해 주세요"처럼 대상 없이 실행을 맡기는 말
  /^(?:(?:네|예|응|어|그래|좋아|하모|그려)[,\s]*)?(?:바로\s*|지금\s*|빨리\s*|다시\s*|한\s*번\s*더\s*)?(?:해\s*(?:줘|주세요|주소|도라|주이소|주라)|그렇게\s*해\s*(?:줘|주세요|주소)?|진행\s*(?:해|시켜)\s*(?:줘|주세요)?)$/,
  // "네 살게예", "빌릴게유"처럼 짧게 하겠다고 하는 말(사투리 어미 포함)
  /^(?:(?:네|예|응|어|하모|그려)[,\s]*)?(?:그걸로\s*|그거로\s*|이걸로\s*)?(?:살게|살께|살래|빌릴게|빌릴께|빌릴래|올릴게|올릴께|할게|할께)(?:요|예|유|용)?$/,
  // "구매해줘", "바로 사 줘", "대여 예약해 주이소"처럼 분명한 실행 요청
  /(?:구매|구입|대여|예약|신청|진행|등록|올려|빌려|수정|고쳐|(?<![가-힣])사)\s*(?:해\s*)?(?:줘|주세요|줄래|주실래요|주소|도라|주이소|주라|드려요|부탁|해요|할게요|할게|할께|합니다|하자|할래요|하이소)/,
  /(?:그걸로|그거로|이걸로|이거로|그것으로|이것으로)\s*(?:해|할게|예약|올려|진행|부탁)/,
  /(?:그거|그걸|이거|이걸)\s*(?:할게요|할게|할래요|살게요|빌릴게요)/,
  // 짧은 동의·승낙("좋네", "알겠어요", "당연하죠", "ㄱㄱ", "예스", "승인")
  /^(?:넵+|넹|옙|예스|yes|yep|ya|y|좋네(?:요)?|좋다|좋지(?:요)?|좋죠|당연하(?:지|죠|죠\s*뭐)|당연히(?:요)?|물론(?:이죠|이지|입니다|이에요)?|알겠(?:어|어요|습니다)|알았(?:어|어요|습니다)|ㄱㄱ+|고고+|가자|가즈아|찬성(?:이에요|입니다)?|동의(?:해|해요|합니다)?|승인|확정|오키(?:도키)?|그래그래|응응|네네|예예예)$/i,
  // 확인 카드에 대한 승인("승인할게", "확정해 주세요", "동의합니다")
  /^(?:(?:네|예|응|좋아|좋아요|그래)[,\s]*)?(?:승인|확정|동의)\s*(?:할게|할께|할래|합니다|해요|해|하자|하겠습니다|해\s*(?:줘|주세요|주이소|주소))(?:요)?$/,
  // 요청을 보내 달라는 말("요청 보내줘", "보내 주세요", "응 보내")
  /^(?:(?:네|예|응|좋아|그래)[,\s]*)?(?:요청\s*)?(?:보내|보내줘|보내\s*주세요|보내요|보내자|보낼게(?:요)?|보내\s*줄래)$/,
  // "그렇게 하자", "이대로 해 주세요", "그대로 진행"
  /^(?:(?:네|예|응|좋아|그래)[,\s]*)?(?:그렇게|그걸로|그거로|이걸로|이거로|이대로|그대로)\s*(?:해|하자|할게|할께|진행|진행해|가자|가요|하죠)?(?:\s*(?:요|줘|주세요))?$/,
  // "부탁해", "부탁할게요"
  /^(?:(?:네|예|응)[,\s]*)?부탁(?:해|해요|할게|할게요|할께요|드릴게요|드립니다|합니다|드려요)?$/,
  // "2번"처럼 번호만 말한 것은 매물을 고른 것이지 실행 승인이 아니다. 실행 동사가 함께 있을 때만 긍정으로 본다.
  /^\d+\s*번(?:\s*(?:으로|로))?\s*(?:해\s*(?:줘|주세요)|할게요|예약|진행)/,
];
// "승인 안 할게", "보내지 마", "나중에 할게"처럼 부정·보류가 섞이면 긍정으로 보지 않는다.
const NEGATIVE_OR_UNSURE = /(?:아니|안\s*돼|안돼|싫|별로|비싸|다른\s*(?:거|것)|글쎄|생각해\s*볼|모르겠|잠깐|잠시만|말고|취소|안\s*(?:할|해|보낼|보내|살|빌릴|하|승인)|지\s*마|하지\s*말|나중에|그만|아직|보류|멈춰|중지)/;

export function isAffirmative(text) {
  const raw = String(text || "").trim();
  if (!raw) return false;
  if (/[?？]\s*$/.test(raw)) return false;
  const normalized = raw.replace(/[.!~…,\s]+$/g, "").replace(/^[\s,]+/, "").trim();
  if (!normalized || NEGATIVE_OR_UNSURE.test(normalized)) return false;
  if (/^(?:음+|흠+|어\.{2,})/.test(normalized)) return false;
  const lead = normalized.replace(/^(?:네네|네|넵|예|응응|응|좋아요|좋아|그래|ㅇㅇ|오케이|ok)[,\s]+/i, "");
  return AFFIRMATIVE.some((pattern) => pattern.test(normalized) || pattern.test(lead));
}
